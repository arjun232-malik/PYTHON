marks=['h','d','a','t','j','a']
marks.append(56) #add element at the end
print(marks)
marks.sort() #arrange the list in ascending order
print(marks)
marks.sort(reverse=True) #arrange the list in descending order
print(marks)
marks.reverse() #ye list ko reverse me arrange kr deta hai 
print(marks)
marks.insert(2,'y') #iss hum koi sublist ko add kr skte hai list me 
print(marks)
marks.remove('a') #ye function uss element ke first occurrence ko remove kr deta hai
print(marks)
marks.pop(1) #ye function uss element ko remove kr deta hai 
print(marks)